"""Per-drawing registration for Myuuel's cross-legged sheets (the kit only ships it for standing and perch sheets).
Each drawing is aligned on her seat — the crossed legs resting on the floor — the way the standing sheets are
aligned on her feet: slide the bottom band of the silhouette sideways until it best overlaps the pose's first
drawing, and put the bottom edge on the floor line. Writes src/renderer/seated-registration.js.
Run: python tools/register-seated.py"""
import json, re
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / 'assets/myuuel/motion-kit'
sheets = {s['id']: s for s in json.loads((KIT / 'approved-sheets.json').read_text())}
kit_reg = json.loads(re.search(r'=(\{.*\})', (KIT / 'rig/motion-registration.js').read_text(), re.S).group(1))
BAND = 70  # px of silhouette above the floor that count as "the seat"

def masks(sid):
    im = np.array(Image.open(KIT / sheets[sid]['image']).convert('RGBA'))[..., 3] > 40
    return [im[(f // 4) * 512:(f // 4) * 512 + 512, (f % 4) * 384:(f % 4) * 384 + 384] for f in range(8)]

def floor_y(m):
    ys = np.nonzero(m)[0]; return float(np.percentile(ys, 99.6))

def seat(m):
    y = int(round(floor_y(m))); return m[max(0, y - BAND):y + 1]

def best_shift(ref, cur, span=28):
    h = min(ref.shape[0], cur.shape[0]); ref, cur = ref[-h:], cur[-h:]
    best, score = 0, -1
    for s in range(-span, span + 1):
        sh = np.roll(cur, -s, axis=1)  # undo a shift of s
        inter = np.logical_and(ref, sh).sum(); union = np.logical_or(ref, sh).sum()
        if union and inter / union > score: best, score = s, inter / union
    return best, score

out, report = {}, []
for sid, s in sheets.items():
    if s['posture'] != 'Sitting' or s['support'] != 'platform' or sid in kit_reg: continue
    ms = masks(sid); ref = seat(ms[0])
    ys, xs = np.nonzero(ref); x0 = float(xs.mean())
    anchors = []
    for f, m in enumerate(ms):
        shift, iou = best_shift(ref, seat(m))
        anchors.append([round(x0 + shift, 1), round(floor_y(m), 1)])
        report.append(f'{sid} f{f}: shift {shift:+d}px  seat overlap {iou:.2f}')
    out[sid] = anchors

js = ('/* Generated by tools/register-seated.py — per-drawing seat registration for the cross-legged sheets.\n'
      '   [x, y] is the point in each 384x512 drawing that lands on the floor anchor (192, 464). */\n'
      'window.MyuuelSeatedRegistration=' + json.dumps(out) + ';\n')
(ROOT / 'src/renderer/seated-registration.js').write_text(js)
print('\n'.join(report))

# ── Sheet scale (AI Discussion's per-sheet registration scale) ──
# The artist drew Myuuel at slightly different sizes in different sheets (her head is 197–208 px wide), so a pose change
# could make her grow or shrink by ~5%. Her head is the steadiest size cue, so each sheet gets the factor that brings its
# median head width to the standing Idle Blink sheet's. The scale is applied around the floor anchor, so feet and seat
# stay planted. Reviewed gesture sheets keep scale 1 (their face pivots are authored at that size).
REFERENCE = '01-idle-blink'
REVIEWED = {'02-listening', '05-happy-wave'}

def head_width(m):
    top = int(np.nonzero(m.any(1))[0][0]); best = 0
    for o in range(20, 130, 4):
        xs = np.nonzero(m[top + o])[0]
        if not len(xs): continue
        run = cur = 1
        for a, b in zip(xs, xs[1:]):
            cur = cur + 1 if b == a + 1 else 1; run = max(run, cur)
        best = max(best, run)
    return best

widths = {sid: float(np.median([head_width(m) for m in masks(sid)])) for sid in sheets}
scale = {sid: (1.0 if sid in REVIEWED else round(widths[REFERENCE] / w, 4)) for sid, w in widths.items()}
with open(ROOT / 'src/renderer/seated-registration.js', 'a') as fh:
    fh.write('/* Per-sheet draw scale so she is the same size in every pose (reference: ' + REFERENCE + ' head width). */\n'
             'window.MyuuelSheetScale=' + json.dumps(scale) + ';\n')
print('\n'.join(f'{sid}: head {widths[sid]:.0f}px -> scale {scale[sid]}' for sid in sorted(scale)))
